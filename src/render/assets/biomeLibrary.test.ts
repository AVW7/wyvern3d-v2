import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { BIOME_PALETTES } from '@/scenes/BiomeWorld/atmosphere/biomePalettes'
import { BIOME_WORLD_RADIUS } from '@/scenes/BiomeWorld/terrain/biomeHeight'
import { BIOME_DRESSING, layerAtlas } from './biomeLibrary'
import { ARCANE_PROP_ATLAS, BIOME_PROP_ATLAS, BONE_PROP_ATLAS, CORRUPT_PROP_ATLAS, FUNGAL_PROP_ATLAS, PROP_ATLAS, REED_PROP_ATLAS, RUIN_PROP_ATLAS, TERRAIN_PROP_ATLAS, WATER_PROP_ATLAS } from './manifest'

interface LibraryManifest {
  props: { id: string; license: { status: string } }[]
}

const manifest: LibraryManifest = JSON.parse(
  readFileSync(new URL('../../../scripts/biome-library.json', import.meta.url), 'utf8'),
)
const biomeProps = new Set(manifest.props.map((entry) => entry.id))

/**
 * Prop names inside a built GLB.
 *
 * The bone atlas is generated by scripts/build-bone-props.mjs rather than
 * declared in scripts/biome-library.json, so there is no manifest to check it
 * against — read the file itself. Names live in the glTF JSON chunk, which is
 * all this needs to see.
 */
function propsInGlb(publicPath: string): Set<string> {
  const file = readFileSync(new URL(`../../../public${publicPath}`, import.meta.url))
  const jsonLength = file.readUInt32LE(12)
  const gltf = JSON.parse(file.subarray(20, 20 + jsonLength).toString('utf8'))
  const names = new Set<string>()
  for (const node of gltf.nodes ?? []) {
    if (typeof node.name === 'string') names.add(node.name)
    if (typeof node.extras?.name === 'string') names.add(node.extras.name)
  }
  return names
}

/** Atlases built from code, which have no manifest to check against. */
const GENERATED_ATLASES: Record<string, Set<string>> = {
  [BONE_PROP_ATLAS]: propsInGlb(BONE_PROP_ATLAS),
  [WATER_PROP_ATLAS]: propsInGlb(WATER_PROP_ATLAS),
  [FUNGAL_PROP_ATLAS]: propsInGlb(FUNGAL_PROP_ATLAS),
  [RUIN_PROP_ATLAS]: propsInGlb(RUIN_PROP_ATLAS),
  [ARCANE_PROP_ATLAS]: propsInGlb(ARCANE_PROP_ATLAS),
  [CORRUPT_PROP_ATLAS]: propsInGlb(CORRUPT_PROP_ATLAS),
  [REED_PROP_ATLAS]: propsInGlb(REED_PROP_ATLAS),
  [TERRAIN_PROP_ATLAS]: propsInGlb(TERRAIN_PROP_ATLAS),
}

describe('biome dressing library', () => {
  it('dresses every biome the world can show', () => {
    for (const biome of Object.keys(BIOME_PALETTES)) {
      expect(BIOME_DRESSING[biome], `${biome} has no dressing`).toBeDefined()
      expect(BIOME_DRESSING[biome]?.length ?? 0).toBeGreaterThan(0)
    }
  })

  it('only references props that the atlas actually builds', () => {
    for (const [biome, layers] of Object.entries(BIOME_DRESSING)) {
      for (const layer of layers) {
        if (layerAtlas(layer) === PROP_ATLAS) continue
        const generated = GENERATED_ATLASES[layerAtlas(layer)]
        if (generated) {
          expect(generated.has(layer.prop), `${biome}: ${layer.prop} is not in its atlas`).toBe(true)
          continue
        }
        expect(layerAtlas(layer)).toBe(BIOME_PROP_ATLAS)
        expect(biomeProps.has(layer.prop), `${biome}: unknown prop ${layer.prop}`).toBe(true)
      }
    }
  })

  it('keeps placements inside the world and within the density budget', () => {
    for (const [biome, layers] of Object.entries(BIOME_DRESSING)) {
      const total = layers.reduce((sum, layer) => sum + layer.count, 0)
      expect(total, `${biome} scatters ${total} props`).toBeLessThanOrEqual(200)
      for (const layer of layers) {
        expect(layer.radius[0]).toBeLessThanOrEqual(layer.radius[1])
        expect(layer.radius[1], `${biome}: ${layer.prop} reaches past the world edge`).toBeLessThanOrEqual(BIOME_WORLD_RADIUS)
        expect(layer.scale[0]).toBeGreaterThan(0)
        expect(layer.scale[0]).toBeLessThanOrEqual(layer.scale[1])
      }
    }
  })

  it('places nothing outside the world radius the terrain builds', () => {
    // biomeLibrary carries its own copy of the radius so that render/ does not
    // import from scenes/. This is the check that keeps the two in step.
    const reach = Math.max(...Object.values(BIOME_DRESSING).flatMap((layers) => layers.map((layer) => layer.radius[1])))
    expect(reach).toBe(BIOME_WORLD_RADIUS - 12)
  })

  it('gives every biome that claims bones a bone layer, sparsely', () => {
    // The four biomes whose character profile claims `bone`. Before the bone
    // atlas, none of them could show one, and barrens showed none of its five
    // traits at all.
    for (const biome of ['mountain', 'ashland', 'tundra', 'barrens']) {
      const layers = BIOME_DRESSING[biome]?.filter((layer) => layerAtlas(layer) === BONE_PROP_ATLAS) ?? []
      expect(layers.length, `${biome} claims bone but scatters none`).toBeGreaterThan(0)
      for (const layer of layers) {
        // A ribcage is a story; a field of them is wallpaper.
        const cap = layer.prop === 'prop.bone.scatter' ? 12 : 5
        expect(layer.count, `${biome} ${layer.prop}`).toBeLessThanOrEqual(cap)
        expect(layer.wind, `${layer.prop} should not sway`).toBeUndefined()
      }
    }
  })

  it('builds every prop the generated atlases promise', () => {
    for (const prop of ['prop.bone.ribcage', 'prop.bone.skull', 'prop.bone.scatter']) {
      expect(GENERATED_ATLASES[BONE_PROP_ATLAS]?.has(prop), `${prop} missing`).toBe(true)
    }
    for (const prop of ['prop.water.pool', 'prop.water.creek', 'prop.water.puddle']) {
      expect(GENERATED_ATLASES[WATER_PROP_ATLAS]?.has(prop), `${prop} missing`).toBe(true)
    }
    for (const prop of ['prop.fungal.cluster', 'prop.fungal.shelf', 'prop.fungal.giant']) {
      expect(GENERATED_ATLASES[FUNGAL_PROP_ATLAS]?.has(prop), `${prop} missing`).toBe(true)
    }
    for (const prop of ['prop.ruin.column', 'prop.ruin.wall', 'prop.ruin.rubble']) {
      expect(GENERATED_ATLASES[RUIN_PROP_ATLAS]?.has(prop), `${prop} missing`).toBe(true)
    }
    for (const prop of ['prop.arcane.runestone', 'prop.arcane.circle', 'prop.arcane.focus']) {
      expect(GENERATED_ATLASES[ARCANE_PROP_ATLAS]?.has(prop), `${prop} missing`).toBe(true)
    }
    for (const prop of ['prop.corrupt.growth', 'prop.corrupt.scar', 'prop.corrupt.bloom']) {
      expect(GENERATED_ATLASES[CORRUPT_PROP_ATLAS]?.has(prop), `${prop} missing`).toBe(true)
    }
    for (const prop of ['prop.reed.bed', 'prop.reed.cattail', 'prop.reed.tussock']) {
      expect(GENERATED_ATLASES[REED_PROP_ATLAS]?.has(prop), `${prop} missing`).toBe(true)
    }
    for (const prop of ['snag', 'deadfall', 'dune', 'drift', 'vent', 'fumarole']) {
      expect(GENERATED_ATLASES[TERRAIN_PROP_ATLAS]?.has(`prop.terrain.${prop}`), `${prop} missing`).toBe(true)
    }
  })

  it('gives every biome that claims a terrain feature the matching prop', () => {
    // One atlas serves three traits here, so the claim has to be checked per
    // prop rather than per atlas.
    const CLAIMS: Record<string, string[]> = {
      forest: ['snag', 'deadfall'],
      barrens: ['snag', 'deadfall', 'dune', 'drift', 'vent', 'fumarole'],
      tundra: ['dune', 'drift'],
      ashland: ['vent', 'fumarole'],
    }
    for (const [biome, wanted] of Object.entries(CLAIMS)) {
      const scattered = new Set(
        (BIOME_DRESSING[biome] ?? [])
          .filter((l) => layerAtlas(l) === TERRAIN_PROP_ATLAS)
          .map((l) => l.prop.replace('prop.terrain.', '')),
      )
      for (const want of wanted) {
        expect(scattered.has(want), `${biome} should scatter ${want}`).toBe(true)
      }
    }
  })

  it('gives the wetland biomes reeds, and lets them sway', () => {
    for (const biome of ['marsh', 'swamp']) {
      const layers = BIOME_DRESSING[biome]?.filter((l) => layerAtlas(l) === REED_PROP_ATLAS) ?? []
      expect(layers.length, `${biome} claims reed but scatters none`).toBeGreaterThan(0)
      for (const layer of layers) {
        expect(layer.wind, `${layer.prop} should sway`).toBeGreaterThan(0)
        expect(layer.castShadow).toBe(false)
      }
    }
  })

  it('gives every biome that claims corruption a corrupt layer', () => {
    for (const biome of ['jungle', 'barrens', 'spire']) {
      const layers = BIOME_DRESSING[biome]?.filter((l) => layerAtlas(l) === CORRUPT_PROP_ATLAS) ?? []
      expect(layers.length, `${biome} claims corrupt but scatters none`).toBeGreaterThan(0)
      for (const layer of layers) {
        expect(layer.color, `${layer.prop} in ${biome} needs a biome tint`).toBeDefined()
      }
    }
  })

  it('gives every biome that claims arcane a worked-stone layer', () => {
    for (const biome of ['cavern', 'grove', 'spire']) {
      const layers = BIOME_DRESSING[biome]?.filter((l) => layerAtlas(l) === ARCANE_PROP_ATLAS) ?? []
      expect(layers.length, `${biome} claims arcane but scatters none`).toBeGreaterThan(0)
      for (const layer of layers) {
        expect(layer.color, `${layer.prop} in ${biome} needs a biome tint`).toBeDefined()
      }
    }
  })

  it('gives every biome that claims ruins a ruin layer', () => {
    for (const biome of ['coast', 'moor', 'jungle']) {
      const layers = BIOME_DRESSING[biome]?.filter((l) => layerAtlas(l) === RUIN_PROP_ATLAS) ?? []
      expect(layers.length, `${biome} claims ruin but scatters none`).toBeGreaterThan(0)
      for (const layer of layers) {
        expect(layer.color, `${layer.prop} in ${biome} needs a biome tint`).toBeDefined()
        expect(layer.wind, 'masonry is rigid').toBeUndefined()
      }
    }
  })

  it('gives every biome that claims fungus a fungal layer', () => {
    for (const biome of ['swamp', 'cavern', 'jungle']) {
      const layers = BIOME_DRESSING[biome]?.filter((l) => layerAtlas(l) === FUNGAL_PROP_ATLAS) ?? []
      expect(layers.length, `${biome} claims fungal but scatters none`).toBeGreaterThan(0)
      for (const layer of layers) {
        expect(layer.color, `${layer.prop} in ${biome} needs a biome tint`).toBeDefined()
        expect(layer.wind, 'fungus is rigid').toBeUndefined()
      }
    }
  })

  it('waters only the biomes that have no water body of their own', () => {
    // marsh, swamp, coast and ashland get a full animated surface from
    // biomeWater.ts. A pool prop there is redundant at best, and at worst sits
    // below the bog line where nothing ever sees it.
    const FLOODED = ['marsh', 'swamp', 'coast', 'ashland']
    for (const [biome, layers] of Object.entries(BIOME_DRESSING)) {
      const waterLayers = layers.filter((layer) => layerAtlas(layer) === WATER_PROP_ATLAS)
      if (FLOODED.includes(biome)) {
        expect(waterLayers, `${biome} already has a water body`).toHaveLength(0)
      }
    }
    for (const biome of ['forest', 'jungle']) {
      const waterLayers = BIOME_DRESSING[biome]?.filter((l) => layerAtlas(l) === WATER_PROP_ATLAS) ?? []
      expect(waterLayers.length, `${biome} claims freshwater but scatters none`).toBeGreaterThan(0)
      for (const layer of waterLayers) {
        expect(layer.castShadow, 'flat water should not cast a shadow').toBe(false)
        expect(layer.wind, 'water is rigid geometry').toBeUndefined()
      }
    }
  })
})
